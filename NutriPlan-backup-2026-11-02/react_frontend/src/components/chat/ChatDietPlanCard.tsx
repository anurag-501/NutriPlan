import { Save } from "lucide-react";
import type { GymPlan } from "@/types/recipe";

interface ChatDietPlanCardProps {
  plan: GymPlan;
  savedPlanExists: boolean;
  onSave: (plan: GymPlan) => void;
}

export default function ChatDietPlanCard({ plan, savedPlanExists, onSave }: ChatDietPlanCardProps) {
  const calorieRange = plan.targets?.target_calories;
  const proteinRange = plan.targets?.protein_g_range;
  return <article className="rounded-xl border border-primary/25 bg-primary/[0.03] p-3 text-card-foreground" aria-label="Generated diet plan">
    <div className="flex flex-wrap items-start justify-between gap-2">
      <div>
        <h3 className="font-semibold">Your meal plan draft</h3>
        <p className="mt-1 text-xs text-muted-foreground">Generated by NutriPlan’s existing recipe recommendation engine.</p>
      </div>
      {calorieRange && <div className="rounded-lg bg-background px-2.5 py-1.5 text-right text-xs">
        <p className="font-semibold">{calorieRange[0]}–{calorieRange[1]} kcal/day estimate</p>
        {proteinRange && <p className="text-muted-foreground">Protein {proteinRange[0]}–{proteinRange[1]} g/day</p>}
      </div>}
    </div>

    <div className="mt-3 space-y-2">
      {plan.meals.map((meal) => <details key={meal.meal_name} className="rounded-lg border bg-background px-3 py-2">
        <summary className="cursor-pointer text-sm font-medium">{meal.meal_name} <span className="text-xs font-normal text-muted-foreground">· about {meal.recommended_calories} kcal</span></summary>
        <ol className="mt-2 list-decimal space-y-1 pl-5 text-xs">
          {meal.recipes.map((recipe) => <li key={recipe.recipe_id}>
            <span className="font-medium">{recipe.Name}</span> · {Math.round(recipe.Calories)} kcal · {Math.round(recipe.ProteinContent)} g protein
            <details className="ml-1 inline-block align-top">
              <summary className="cursor-pointer text-primary underline underline-offset-2">recipe</summary>
              <div className="mt-1 rounded-md border bg-card p-2 text-foreground">
                <p><strong>Ingredients:</strong> {recipe.RecipeIngredientParts.join(", ") || "Unavailable"}</p>
                <p className="mt-1"><strong>Instructions:</strong> {recipe.RecipeInstructions.join(" ") || "Unavailable"}</p>
                <p className="mt-1 text-muted-foreground">Ingredient quantities are not available. Nutrition is dataset-reported per recorded recipe serving; check labels and cross-contact separately.</p>
              </div>
            </details>
          </li>)}
        </ol>
      </details>)}
    </div>

    {plan.limitations.length > 0 && <details className="mt-3 text-xs text-muted-foreground">
      <summary className="cursor-pointer font-medium">Nutrition notes and limitations</summary>
      <ul className="mt-1 list-disc space-y-1 pl-5">{plan.limitations.map((limitation, index) => <li key={index}>{limitation}</li>)}</ul>
      <p className="mt-1">Source: {plan.nutrition_source}</p>
    </details>}
    <button type="button" onClick={() => onSave(plan)} className="mt-3 inline-flex min-h-10 items-center gap-2 rounded-lg bg-primary px-3 py-2 text-xs font-semibold text-primary-foreground">
      <Save className="h-4 w-4" aria-hidden="true" />{savedPlanExists ? "Replace saved plan" : "Save to My Plan"}
    </button>
    <p className="mt-1 text-[10px] text-muted-foreground">This draft is not saved until you choose the button.</p>
  </article>;
}
